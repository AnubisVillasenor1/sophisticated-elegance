type PostSeed = {
  title: string;
  excerpt: string;
  body: string;
  visibility: Post["visibility"];
  cover: CoverKey;
  tags: string[];
  mature?: boolean;
  priceMXN?: number;
  likes: number;
  comments: number;
  daysAgo: number;
  tier?: 1 | 2 | 3;
};

function makePosts(creatorId: string, seeds: PostSeed[], tiers: Tier[]): Post[] {
  return seeds.map((p, i) => ({
    id: `${creatorId}-p${i + 1}`,
    creatorId,
    title: p.title,
    excerpt: p.excerpt,
    body: p.body,
    visibility: p.visibility,
    tierId: p.tier ? (tiers[p.tier - 1]?.id ?? null) : null,
    priceMXN: p.priceMXN ?? 0,
    createdAt: day(-p.daysAgo),
    likes: p.likes,
    comments: p.comments,
    cover: p.cover,
    tags: p.tags,
    mature: p.mature ?? false,
  }));
}

type ClipSeed = {
  title: string;
  description: string;
  category: string;
  priceMXN: number;
  duration: string;
  cover: CoverKey;
  sales: number;
  daysAgo: number;
  mature?: boolean;
};

function makeClips(creatorId: string, seeds: ClipSeed[]): Clip[] {
  return seeds.map((c, i) => ({
    id: `${creatorId}-c${i + 1}`,
    creatorId,
    title: c.title,
    description: c.description,
    category: c.category,
    priceMXN: c.priceMXN,
    duration: c.duration,
    cover: c.cover,
    sales: c.sales,
    createdAt: day(-c.daysAgo),
    mature: c.mature ?? false,
  }));
}

type RoomSeed = {
  title: string;
  description: string;
  status: LiveRoom["status"];
  access: LiveRoom["access"];
  ticketPriceMXN: number;
  startsAt: string;
  durationMin: number;
  viewers: number;
  capacity: number;
  cover: CoverKey;
  tipsMXN: number;
};

function makeRooms(creatorId: string, seeds: RoomSeed[]): LiveRoom[] {
  return seeds.map((r, i) => ({ id: `${creatorId}-r${i + 1}`, creatorId, ...r }));
}

function makeOffers(
  creatorId: string,
  seeds: Omit<CustomOffer, "id" | "creatorId">[],
): CustomOffer[] {
  return seeds.map((o, i) => ({ id: `${creatorId}-o${i + 1}`, creatorId, ...o }));
}

function makeBundles(creatorId: string, seeds: Omit<Bundle, "id" | "creatorId">[]): Bundle[] {
  return seeds.map((b, i) => ({ id: `${creatorId}-b${i + 1}`, creatorId, ...b }));
}

